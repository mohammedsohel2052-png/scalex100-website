// Projects Survey of India state boundaries (DataMeet, CC BY 4.0) into static SVG paths.
import { readFileSync, writeFileSync } from 'node:fs';
import { geoMercator, geoPath } from 'd3-geo';

const states = JSON.parse(readFileSync(new URL('./states.json', import.meta.url)));
const outline = JSON.parse(readFileSync(new URL('./outline.json', import.meta.url)));
// d3-geo expects clockwise outer rings; GeoJSON from mapshaper is RFC 7946 (counter-clockwise). Reverse rings.
const rewind = g => { if (!g) return g; if (g.type === 'Polygon') g.coordinates.forEach(r => r.reverse()); else if (g.type === 'MultiPolygon') g.coordinates.forEach(p => p.forEach(r => r.reverse())); else if (g.type === 'GeometryCollection') g.geometries.forEach(rewind); return g; };
states.features.forEach(f => rewind(f.geometry));
(outline.features || outline.geometries).forEach(f => rewind(f.geometry || f));
const W = 1000, H = 1100;
const proj = geoMercator().fitExtent([[24, 24], [W - 24, H - 24]], outline);
const path = geoPath(proj).digits(1);

const slug = s => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
const stateOut = states.features.map(f => ({ id: slug(f.properties.ST_NM), name: f.properties.ST_NM, d: path(f) }));
const outlineD = (outline.features || outline.geometries).map(f => path(f)).join('');

// [lon, lat]
