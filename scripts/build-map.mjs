const cityOut = Object.fromEntries(Object.entries(cities).map(([k, ll]) => { const [x, y] = proj(ll); return [k, [Math.round(x * 10) / 10, Math.round(y * 10) / 10]]; }));

// bounding boxes of focus states (for camera framing)
const bbox = name => { const f = states.features.find(s => s.properties.ST_NM === name); const [[x0, y0], [x1, y1]] = path.bounds(f); return [x0, y0, x1, y1].map(v => Math.round(v)); };
const boxes = { maharashtra: bbox('Maharashtra'), bihar: bbox('Bihar'), delhi: bbox('Delhi'), haryana: bbox('Haryana') };

const out = `// Generated by scripts/build-map.mjs — do not edit by hand.
// Boundaries: Survey of India state map via DataMeet (CC BY 4.0) https://github.com/datameet/maps
export const MAP_W = ${W};
export const MAP_H = ${H};
export const STATES: { id: string; name: string; d: string }[] = ${JSON.stringify(stateOut)};
export const OUTLINE = ${JSON.stringify(outlineD)};
export const CITIES: Record<string, [number, number]> = ${JSON.stringify(cityOut)};
export const BOXES: Record<string, [number, number, number, number]> = ${JSON.stringify(boxes)};
`;
writeFileSync(new URL('../src/data/indiaMap.ts', import.meta.url), out);
